"""Generate per-stage LLaMA-Factory YAMLs for a layer-stacked pretraining run.

A high-level pilot spec describes the run: preset name, three stage-spec JSONs,
LR/max_steps per stage. The script emits 3 LLaMA-Factory pretraining YAMLs and
2 transition shell scripts that the LLaMA-Factory sbatch chain consumes.

Usage::

    python scripts/generate_stage_yaml.py \\
        --pilot stack_50m_b_dn \\
        --stage1-spec configs/torchtitan/stacking/specs/50m_b_dn_stage1.json \\
        --stage2-spec configs/torchtitan/stacking/specs/50m_b_dn_stage2.json \\
        --stage3-spec configs/torchtitan/stacking/specs/50m_b_dn_stage3.json \\
        --max-steps 200 1000 2800 \\
        --lr 3e-4 1.5e-4 1e-4 \\
        --dataset fineweb_edu_1B_train \\
        --dataset-dir /shared/.../fineweb-edu-1B \\
        --tokenizer /shared/.../SmolLM2 \\
        --bootstrap-checkpoint /path/to/stage1_init \\
        --output-dir ./outputs/stacking/stack_50m_b_dn \\
        --yaml-out configs/llama_factory/stacking/stack_50m_b_dn

The first stage's ``model_name_or_path`` points at the bootstrap init checkpoint
(produced by ``scripts/pretrain.py --dry_run``). Subsequent stages point at the
output directory of ``staging.transition`` between stages.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import List

YAML_TEMPLATE = """\
# Auto-generated by scripts/generate_stage_yaml.py — do not hand-edit.
# Stacking pilot {pilot} stage {stage_index}.

### Model Configuration ###
model_name_or_path: {model_path}
trust_remote_code: true

### Data Configuration ###
dataset_dir: {dataset_dir}
dataset: {dataset}
cutoff_len: {cutoff_len}
preprocessing_num_workers: 16

### Training Stage ###
stage: pt
do_train: true
finetuning_type: full

### Output Configuration ###
output_dir: {output_dir}
logging_dir: {output_dir}/logs
overwrite_output_dir: false
run_name: {run_name}

### Training Hyperparameters ###
per_device_train_batch_size: {per_device_batch_size}
per_device_eval_batch_size: {per_device_batch_size}
gradient_accumulation_steps: {gradient_accumulation_steps}
learning_rate: {lr}
max_steps: {max_steps}
lr_scheduler_type: cosine
warmup_ratio: {warmup_ratio}
weight_decay: 0.1
max_grad_norm: 1.0

### Optimization ###
bf16: true
gradient_checkpointing: true
flash_attn: fa2
optim: adamw_torch

### Logging and Saving ###
logging_steps: 10
include_tokens_per_second: true
include_num_input_tokens_seen: true
save_steps: {save_steps}
save_total_limit: 1

report_to: wandb

### Evaluation ###
do_eval: false

### Misc ###
seed: 42
dataloader_num_workers: 8
dataloader_pin_memory: true
"""


def write_stage_yaml(
    *,
    pilot: str,
    stage_index: int,
    model_path: str,
    dataset_dir: str,
    dataset: str,
    cutoff_len: int,
    output_dir: Path,
    run_name: str,
    per_device_batch_size: int,
    gradient_accumulation_steps: int,
    lr: float,
    max_steps: int,
    save_steps: int,
    warmup_ratio: float,
    yaml_out: Path,
) -> Path:
    yaml_out.parent.mkdir(parents=True, exist_ok=True)
    text = YAML_TEMPLATE.format(
        pilot=pilot,
        stage_index=stage_index,
        model_path=model_path,
        dataset_dir=dataset_dir,
        dataset=dataset,
        cutoff_len=cutoff_len,
        output_dir=str(output_dir),
        run_name=run_name,
        per_device_batch_size=per_device_batch_size,
        gradient_accumulation_steps=gradient_accumulation_steps,
        lr=lr,
        max_steps=max_steps,
        save_steps=save_steps,
        warmup_ratio=warmup_ratio,
    )
    yaml_out.write_text(text)
    return yaml_out


def write_transition_script(
    *,
    pilot: str,
    from_index: int,
    to_index: int,
    from_dir: Path,
    to_dir: Path,
    spec_path: Path,
    init_strategy: str,
    run_probes: bool,
    out_path: Path,
) -> Path:
    """Write a small shell script that invokes the staging.transition CLI."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    script = f"""#!/bin/bash
# Auto-generated stacking-pilot transition script for {pilot}: stage {from_index} -> {to_index}.
set -euo pipefail
python -m umich_slm.staging.transition \\
    --from   {from_dir} \\
    --to     {to_dir} \\
    --config {spec_path} \\
    --init-strategy {init_strategy}{' \\\n    --run-probes' if run_probes else ''}
"""
    out_path.write_text(script)
    out_path.chmod(0o755)
    return out_path


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--pilot", required=True, help="Pilot name (e.g. 'stack_50m_b_dn').")
    p.add_argument("--stage1-spec", required=True, help="Path to StageSpec JSON for stage 1.")
    p.add_argument("--stage2-spec", required=True)
    p.add_argument("--stage3-spec", required=True)
    p.add_argument("--max-steps", nargs=3, type=int, required=True, metavar=("S1", "S2", "S3"))
    p.add_argument("--lr", nargs=3, type=float, required=True, metavar=("L1", "L2", "L3"))
    p.add_argument("--dataset", required=True)
    p.add_argument("--dataset-dir", required=True)
    p.add_argument("--cutoff-len", type=int, default=2048)
    p.add_argument("--per-device-batch-size", type=int, default=8)
    p.add_argument("--gradient-accumulation-steps", type=int, default=16)
    p.add_argument("--save-steps", type=int, default=500)
    p.add_argument("--warmup-ratio", type=float, default=0.05)
    p.add_argument("--bootstrap-checkpoint", required=True,
                   help="Stage-1 model_name_or_path (bootstrap init or pre-pretrain).")
    p.add_argument("--output-dir", required=True,
                   help="Top-level output dir; per-stage subdirs are created under it.")
    p.add_argument("--yaml-out", required=True,
                   help="Output dir for the generated YAMLs and transition scripts.")
    p.add_argument("--init-strategy", default="exact_copy",
                   choices=["exact_copy", "llama_pro_identity"])
    p.add_argument("--run-probes-between-stages", action="store_true")
    args = p.parse_args(argv)

    pilot = args.pilot
    output_root = Path(args.output_dir)
    yaml_dir = Path(args.yaml_out)

    # Stage subdirectories. Stages 2/3 use init dirs produced by transition.
    stage_outputs = [output_root / f"stage_{i}" for i in (1, 2, 3)]
    stage_inits = [None, output_root / "stage_2_init", output_root / "stage_3_init"]
    spec_paths = [Path(args.stage1_spec), Path(args.stage2_spec), Path(args.stage3_spec)]

    for i, (out, init, spec, lr, steps) in enumerate(
        zip(stage_outputs, stage_inits, spec_paths, args.lr, args.max_steps), start=1
    ):
        if i == 1:
            model_path = args.bootstrap_checkpoint
        else:
            model_path = str(init)
        yaml_out = yaml_dir / f"{pilot}_stage{i}.yaml"
        write_stage_yaml(
            pilot=pilot,
            stage_index=i,
            model_path=model_path,
            dataset_dir=args.dataset_dir,
            dataset=args.dataset,
            cutoff_len=args.cutoff_len,
            output_dir=out,
            run_name=f"{pilot}_stage{i}",
            per_device_batch_size=args.per_device_batch_size,
            gradient_accumulation_steps=args.gradient_accumulation_steps,
            lr=lr,
            max_steps=steps,
            save_steps=args.save_steps,
            warmup_ratio=args.warmup_ratio,
            yaml_out=yaml_out,
        )
        print(f"Wrote {yaml_out}")

    # Two transition scripts: stage1 -> stage2, stage2 -> stage3.
    for from_i, to_i in ((1, 2), (2, 3)):
        write_transition_script(
            pilot=pilot,
            from_index=from_i,
            to_index=to_i,
            from_dir=stage_outputs[from_i - 1],
            to_dir=stage_inits[to_i - 1],
            spec_path=spec_paths[to_i - 1],
            init_strategy=args.init_strategy,
            run_probes=args.run_probes_between_stages,
            out_path=yaml_dir / f"{pilot}_transition_{from_i}to{to_i}.sh",
        )
        print(f"Wrote transition script {yaml_dir / f'{pilot}_transition_{from_i}to{to_i}.sh'}")

    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
